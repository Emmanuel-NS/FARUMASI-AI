"""Stage 1: download the raw data.

Sources (all real, human-written text; nothing generated by an LLM):
  * openFDA drug labels (US FDA, public domain) for the WHO essential medicines in scope.
  * MedQuAD (Ben Abacha & Demner-Fushman, 2019): NIH consumer health question-answer pairs.
  * MedicationQA (Ben Abacha et al., 2019): real consumer questions about medicines with
    answers from trusted sources.
  * CLINC150 (Larson et al., 2019): everyday virtual-assistant queries, used as
    out-of-domain examples.
  * ChatDoctor-HealthCareMagic (Li et al., 2023): real patient messages, used to add
    informal consumer-style health questions to the intent training data.

Usage:  python -m pharmqa.data.download
"""
from __future__ import annotations

import io
import json
import time
import zipfile

import requests
from datasets import load_dataset
from tqdm import tqdm

from pharmqa.config import RAW
from pharmqa.data.essential_medicines import ESSENTIAL_MEDICINES

OPENFDA_URL = "https://api.fda.gov/drug/label.json"
MEDQUAD_ZIP = "https://github.com/abachaa/MedQuAD/archive/refs/heads/master.zip"

# Label sections that a pharmacist would use to answer patient questions.
PATIENT_SECTIONS = [
    "purpose", "indications_and_usage", "dosage_and_administration", "contraindications",
    "warnings_and_cautions", "warnings", "boxed_warning", "adverse_reactions",
    "drug_interactions", "overdosage", "pregnancy", "pregnancy_or_breast_feeding",
    "use_in_specific_populations", "information_for_patients", "do_not_use",
    "ask_doctor", "ask_doctor_or_pharmacist", "stop_use", "when_using",
    "keep_out_of_reach_of_children", "storage_and_handling", "directions",
]


def _label_score(label: dict) -> int:
    return sum(1 for s in PATIENT_SECTIONS if label.get(s))


def fetch_openfda(per_drug: int = 5) -> None:
    out = RAW / "openfda_labels.jsonl"
    session = requests.Session()
    kept = 0
    with out.open("w", encoding="utf-8") as fh:
        for inn, us_name in tqdm(ESSENTIAL_MEDICINES.items(), desc="openFDA"):
            params = {"search": f'openfda.generic_name:"{us_name}"', "limit": per_drug}
            for attempt in range(3):
                r = session.get(OPENFDA_URL, params=params, timeout=30)
                if r.status_code in (200, 404):
                    break
                time.sleep(2 * (attempt + 1))
            if r.status_code != 200:
                continue
            labels = r.json().get("results", [])
            if not labels:
                continue
            # Keep the label with the richest patient-facing content.
            best = max(labels, key=_label_score)
            record = {
                "drug": inn,
                "us_name": us_name,
                "set_id": best.get("set_id"),
                "sections": {s: " ".join(best[s]) for s in PATIENT_SECTIONS if best.get(s)},
            }
            fh.write(json.dumps(record, ensure_ascii=False) + "\n")
            kept += 1
            time.sleep(0.3)  # stay well under the anonymous rate limit
    print(f"openFDA: kept labels for {kept}/{len(ESSENTIAL_MEDICINES)} medicines -> {out}")


def fetch_medquad() -> None:
    target = RAW / "medquad"
    if target.exists() and any(target.rglob("*.xml")):
        print("MedQuAD already downloaded")
        return
    r = requests.get(MEDQUAD_ZIP, timeout=300)
    r.raise_for_status()
    with zipfile.ZipFile(io.BytesIO(r.content)) as zf:
        zf.extractall(target)
    print(f"MedQuAD: {sum(1 for _ in target.rglob('*.xml'))} XML documents -> {target}")


def fetch_hf_datasets() -> None:
    mqa = load_dataset("truehealth/medicationqa")["train"]
    mqa.to_json(RAW / "medicationqa.jsonl")
    print(f"MedicationQA: {len(mqa)} rows")

    clinc = load_dataset("clinc/clinc_oos", "plus")
    names = clinc["train"].features["intent"].names
    with (RAW / "clinc150.jsonl").open("w", encoding="utf-8") as fh:
        for split in ("train", "validation", "test"):
            for row in clinc[split]:
                fh.write(json.dumps({"text": row["text"], "intent": names[row["intent"]], "split": split}) + "\n")
    print("CLINC150: saved all splits")

    # Real patient messages (ChatDoctor / HealthCareMagic, Li et al., 2023). Only the patient
    # side is kept; a 20k random sample is plenty for the consumer-style intent experiment.
    hcm = load_dataset("lavita/ChatDoctor-HealthCareMagic-100k", split="train").shuffle(seed=42).select(range(20000))
    with (RAW / "healthcaremagic_20k.jsonl").open("w", encoding="utf-8") as fh:
        for row in hcm:
            fh.write(json.dumps({"text": row["input"]}, ensure_ascii=False) + "\n")
    print("HealthCareMagic: saved 20k patient messages")


if __name__ == "__main__":
    fetch_medquad()
    fetch_hf_datasets()
    fetch_openfda()
